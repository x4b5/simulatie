export function langDir(code) {
  return LANGS.find((l) => l.code === code)?.dir ?? 'ltr';
}

// Geeft [nederlands, vertaling | null] terug.
export function pair(entry, lang) {
  const nl = entry.nl;
  const other = lang !== 'nl' && entry[lang] && entry[lang] !== nl ? entry[lang] : null;
  return [nl, other];
}
